#!/usr/bin/env node
// @ts-check
/// <reference types="node" />
// 构建 host.js：rolldown 把 host.ts 及其 `./lib/*` 依赖打成单文件 ESM，落在**包根**
// （与源码同目录，故 `import.meta.dirname` 的语义与源码态完全一致）。
// 编排（依赖段外部化、输出守卫、region 正典化、moduleIds 结构性判据）统一住在
// @jayyuen66/dsh-plugin-shared/lib/build-host，一处可改；本文件只声明本仓的入口、产物
// 与生成头。为什么必须有打包这一步、为什么外部化按包名段判——见 shared 同名切面的
// 文件头。不产 .d.ts：插件包对外没有 TS API——dsh 按包名载入运行，没有人 import 它。
import path from "node:path";
import { rolldown } from "rolldown";
import { buildHostEntries } from "@jayyuen66/dsh-plugin-shared/lib/build-host";
import { invokedDirectly, writeArtifact } from "@jayyuen66/dsh-plugin-shared/lib/build-artifacts";

const root = import.meta.dirname;

// 入口名与产物名各只有一处真源：入口表、取产物、落盘与日志都从这两个常量派生。
// 此前 "host.js" 在四处各自手写，改产物名时漏一处就是「构建成功却写错文件」。
const HOST_SOURCE = "host.ts";
const HOST_OUTPUT = "host.js";

/** 生成 host.js 的完整文本。 */
export async function buildHost() {
  const artifacts = await buildHostEntries({
    root,
    rolldown,
    entries: [
      {
        source: HOST_SOURCE,
        output: HOST_OUTPUT,
        header:
          "// GENERATED by build-host.mjs — edit host.ts / lib/*.ts, then run `node build-host.mjs`.\n",
      },
    ],
  });
  const artifact = artifacts.at(0);
  // 判据是「恰好一条」：0 条说明编排没交回产物，多条说明入口表与产物名撞了。
  // 只取第一个会在多条时静默写出一份来路不明的产物，所以两种情况都在这里停住。
  if (artifacts.length !== 1 || artifact === undefined) {
    throw new Error(
      `buildHostEntries 交回的产物清单里 ${HOST_OUTPUT} 应恰好一条，实得 ${artifacts.length} 条（全部产物：${artifacts.map((item) => item.output).join(", ") || "空"}）`,
    );
  }
  return artifact.code;
}

async function main() {
  const out = await buildHost();
  await writeArtifact(path.join(root, HOST_OUTPUT), out);
  console.info(`${HOST_OUTPUT} written:`, Buffer.byteLength(out, "utf8"), "bytes");
}

if (invokedDirectly(import.meta.filename)) {
  try {
    await main();
  } catch (error) {
    // 落盘在构建成功之后，所以走到这里时既有 host.js 一定没被改动——把这条说清楚，
    // 免得把「构建失败」误读成「产物被写坏」。
    console.error("[build-host.mjs] 构建失败，既有 host.js 未被改动：", error);
    process.exitCode = 1;
  }
}
