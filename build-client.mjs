#!/usr/bin/env node
// @ts-check
/// <reference types="node" />
// 构建 client.js：rolldown 把 src/client-entry.ts + lib/transcript.ts 打包为 CJS
// （react 家族精确外置），再包进 window.__ModuleLoader__.load({ id, factory }) UMD
// 外壳。id 取 package.json 的 name，与 dsh.client 模块表键一致。
// 编排（外置判据、store 路径折叠、外壳拼装）统一住在 @jayyuen66/dsh-plugin-shared/
// lib/build-client；本文件只声明入口、生成头与本仓自有的包名同源校验（源码声明形）。
// 运行：node build-client.mjs（或 pnpm build:client）。buildClient() 供测试导入。
import path from "node:path";
import { rolldown } from "rolldown";
import { buildClientBundle } from "@jayyuen66/dsh-plugin-shared/lib/build-client";
import { invokedDirectly, writeArtifact } from "@jayyuen66/dsh-plugin-shared/lib/build-artifacts";

// 单 chunk 断言现在只有 shared 一份；此处转导出，导入方不必改路径。
export { singleEntryChunk } from "@jayyuen66/dsh-plugin-shared/lib/build-artifacts";

const root = import.meta.dirname;

/** 生成 client.js 的完整文本（含 ModuleLoader 外壳）。 */
export async function buildClient() {
  return buildClientBundle({
    root,
    rolldown,
    header:
      "// GENERATED by buildClient() in build-client.mjs — edit src/*.ts + lib/transcript.ts, then run `node build-client.mjs`.",
    verifyName: async ({ pkgName, readSource }) => {
      // 槽位 key 写死在 src 的 BUNDLE_PKG，外壳 id 取自 package.json.name。宿主按包名逐字
      // 匹配模块表键，对不上就是整张卡静默不渲染，而改名在别的环节没有症状。
      // 判据落在**源码声明**上，不落产物：外壳 id 与内联代码里的其它包名常量各自带着同
      // 一个字面量，「产物包含包名」的子串判据在 BUNDLE_PKG 单独漂移时依然通过，等于没有
      // 判据。行首锚点是判据的一部分：没有它时，注释里写的同形片段或字符串里的示例只要
      // 排在真声明之前，就会被 exec 命中而静默返回一个错的值——正好绕过这里要防的漂移。
      const source = await readSource(path.join("src", "client-entry.ts"));
      const declared = /^\s*const\s+BUNDLE_PKG\s*=\s*"[^"\\]*"/mu.exec(source);
      const value = declared?.[0].split('"').at(1);
      // 刻意 fail loud：声明被改名、改成模板串或删掉时，判据无从执行，构建必须停而不是放行。
      if (value === undefined || value === "") {
        throw new Error(
          'build-client：src/client-entry.ts 里找不到 `const BUNDLE_PKG = "…"` 形式的声明，无法校验它与 package.json 的 name 同源。',
        );
      }
      if (value !== pkgName) {
        throw new Error(
          `build-client：src/client-entry.ts 的 BUNDLE_PKG 是 ${JSON.stringify(value)}，package.json 的 name 是 ${JSON.stringify(pkgName)}，两者必须同源。`,
        );
      }
    },
  });
}

async function main() {
  const out = await buildClient();
  await writeArtifact(path.join(root, "client.js"), out);
  console.info("client.js written:", Buffer.byteLength(out, "utf8"), "bytes");
}

if (invokedDirectly(import.meta.filename)) {
  try {
    await main();
  } catch (error) {
    console.error(error);
    process.exitCode = 1;
  }
}
