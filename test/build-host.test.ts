// build-host 防回归：产物 host.js 里的跨包依赖必须是「外部化裸说明符」，而不是被内联。
//
// 为什么值得一条测试（两个坏方向都不报错、只在线上发作）：发布形态下 host.js 躺在
// node_modules 里被 dsh 载入——
//   1) 内联：`@jayyuen66/dsh-plugin-shared/lib/record` 这类**子路径**说明符一旦被打进产物，shared 的
//      模块级状态就在每个插件里各复制一份；rolldown 的 external 字符串项是精确匹配，
//      只列包名会漏掉子路径，故 build-host.mjs 按「包名段」判定（该坑已在脚本注释登记）。
//   2) 残留：产物里只要还剩 `./lib/xxx.ts`，Node 载入即抛 ERR_UNSUPPORTED_NODE_MODULES_
//      TYPE_STRIPPING；而值导入的宿主包从 dependencies **与 peerDependencies** 两张表一起跑掉
//      （只剩 devDependencies）就会被整包内联——体积翻倍正是内联发生了的指纹，故一并钉住。
import { describe, it } from "vitest";
import assert from "node:assert/strict";
import { buildHost } from "../build-host.mjs";
import { hostFreshnessEvidence } from "./host-freshness.ts";

// buildHost() 每次调用都完整跑一遍 rolldown；本文件的多条断言看的是同一份产物，
// 模块级只构建一次并复用（同时保证各断言看到的是同一份字节，而不是几次独立构建）。
let builtOnce: Promise<string> | undefined;

/** 本文件共用的当期产物（首次调用触发构建）。 */
async function builtHost(): Promise<string> {
  builtOnce ??= buildHost();
  return builtOnce;
}

/** 产物里是否以裸说明符 from "<specifier>" 引用：容忍引号类型与空白形态。 */
function importsFrom(out: string, specifier: string): boolean {
  const escaped = specifier.replaceAll(/[.*+?${}()|[\]\\]/gu, String.raw`\$&`);
  return new RegExp(`from\\s*["']${escaped}["']`, "u").test(out);
}

/** 行首声明形态：function/const/let/var/class 五种都算「函数体或类体被内联」。 */
function declares(out: string, name: string): boolean {
  return new RegExp(`^(?:function|const|let|var|class)\\s+${name}\\b`, "mu").test(out);
}

describe("buildHost()", () => {
  it("host.js 与最新构建逐字节一致（改 host.ts / lib/*.ts 后必须 node build-host.mjs）", async () => {
    const { pkgName, pkgDir, onDisk, built } = await hostFreshnessEvidence(import.meta.url);
    assert.equal(
      onDisk,
      built,
      `[${pkgName}] host.js 已过期（磁盘 ${onDisk.length} 字符 / 当期构建 ${built.length} 字符）：` +
        `host.ts（或其依赖）变更后未重建。请运行：cd ${pkgDir} && node build-host.mjs`,
    );
  });

  it("产物 host.js：运行期跨包依赖保持 external（未内联）", async () => {
    const out = await builtHost();
    assert.ok(
      out.startsWith("// GENERATED by build-host.mjs"),
      "产物须带生成标记（勿手改 host.js）",
    );
    // 值导入的包必须列在 dependencies 或 peerDependencies（宿主包落后者，见 publish-manifest
    // 的门禁），否则被内联。这个值导入必须是**宿主 fork**
    // 的 schemastery：只有它的 resolve 会把 .volatile() 字段包成 Volatile 引用（本包全部
    // volatile 设置项都走这条通道），公共 schemastery 既没有 .volatile()、解析出的也仍是普通值
    // （设置卡写进去的值永远读不到 = 续跑开关静默失效）。
    assert.ok(
      importsFrom(out, "@deepseek-ai/schemastery"),
      "@deepseek-ai/schemastery 必须以裸说明符形式留在产物里",
    );
    // 反向锁：不得退回公共 schemastery（两份 schemastery 单例还会让宿主的 volatileForm
    // 判据对不上号）。
    assert.ok(
      !importsFrom(out, "schemastery"),
      "host.js 不得再值导入公共 schemastery（0.1.7 volatile 解析只在宿主 fork 里）",
    );
    // 子路径说明符：external 字符串项匹配不到的那个坑
    assert.ok(
      importsFrom(out, "@deepseek-ai/dsh-brand"),
      "dsh-brand 必须外部化（口径 A；host 半的 SessionId 构造靠它）",
    );
    // 内联判据不绑「行首 + function + 紧接左括号」一种形态：const/let/var/class 声明、
    // 泛型参数与缩进同样算内联已发生（打包器会改写声明形态）。
    assert.ok(!declares(out, "brandString"), "host.js 不得内联 brandString 的函数体");
    // 本包 client 半是**结构性例外**：build-client.mjs 只 external react（浏览器侧解析不了
    // 裸说明符），故 client.js 里仍是内联的 brandString——那条不由外部化裁定消灭。
    assert.ok(
      importsFrom(out, "@deepseek-ai/dsh-typert-protocol"),
      "dsh-typert-protocol 必须外部化（读面的服务基类与注册口都来自宿主）",
    );
    assert.ok(
      importsFrom(out, "@jayyuen66/dsh-plugin-shared/lib/record"),
      "shared/record 必须外部化（SP-D 起 isRecord/fieldOf 单点在 shared，内联即复制判据）",
    );
    // 本包自己的读面代码确已并入单文件：用**声明形态**判，而不是子串 "sessionRescue"——
    // 后者在产物里只出现在一个字符串常量（RESCUE_REMOTE_NAMESPACE）里，拿它当证据等于没证。
    assert.ok(
      declares(out, "SessionRescueRemoteService"),
      "本包读面类须以声明形态出现在单文件产物里（证明本包代码被内联，而非只剩字符串常量）",
    );
  });

  it("产物 host.js：不残留相对说明符的 TS 源文件引用", async () => {
    const out = await builtHost();
    // lib/*.ts 应已被吃进单文件；留着即「发布后 Node 直接拒载」的形态。../ 与 .mts/.cts/.tsx、
    // 以及模板字符串形态的说明符同样致命，故按「引号 + 一到两级 ./ + TS 扩展名 + 引号」判。
    assert.ok(
      !/["'`]\.{1,2}\/[^"'`]*\.(?:ts|mts|cts|tsx)["'`]/u.test(out),
      "不得有 ./x.ts / ../x.ts / ./x.mts 等相对说明符残留",
    );
  });
});

describe("读面基座的外部化面（dsh-typert-protocol）", () => {
  it("remote 标记与服务基类保持裸说明符，不被复制进本包产物", async () => {
    const out = await builtHost();
    assert.ok(
      importsFrom(out, "@deepseek-ai/dsh-typert-protocol"),
      "dsh-typert-protocol 必须外部化",
    );
    assert.ok(
      !declares(out, "TypertRemoteService"),
      "产物不得内联 TypertRemoteService（按声明形态判，不依赖 class 后是否紧跟左花括号）",
    );
  });
});
